-- Script dung so sanh du lieu cua Skymonitor va RK7 (sau khi dong ca chung) xem co bi lech hay khong
SELECT 
    RK.IRESTAURANT   AS RestaurantId,
    R.NAME           AS RestaurantName,
    RK.SHIFTDATE     AS ShiftDate,
    RK.MIDSERVER,
    RK.SHIFTNUM,
    RK.PAYSUM        AS RK_PAYSUM,
    SK.PAYSUM        AS SK_PAYSUM,
    RK.PAYSUM - ISNULL(SK.PAYSUM, 0) AS DIFF_PAYSUM
FROM (
    SELECT 
        GS.IRESTAURANT,
        GS.SHIFTDATE,
        GS.MIDSERVER,
        GS.SHIFTNUM,
        SUM(PB.PAYSUM) AS PAYSUM
    FROM GLOBALSHIFTS GS
    LEFT JOIN ORDERS O ON O.MIDSERVER = GS.MIDSERVER AND O.ICOMMONSHIFT = GS.SHIFTNUM
    LEFT JOIN PRINTCHECKS PC ON PC.MIDSERVER = O.MIDSERVER AND PC.VISIT = O.VISIT
    WHERE PC.STATE = 6
    GROUP BY GS.IRESTAURANT, GS.SHIFTDATE, GS.MIDSERVER, GS.SHIFTNUM
) RK
LEFT JOIN SKYMONITOR_PAYMENTS SK ON SK.MIDSERVER = RK.MIDSERVER AND SK.SHIFTNUM = RK.SHIFTNUM
ORDER BY RK.SHIFTDATE DESC;
